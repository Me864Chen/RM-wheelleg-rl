"""Current 4.SLDASM export; confirmed standing pose, +X-forward body frame.

Continuous actuator limits use a provisional 24 V reference; PD gains remain uncalibrated.
Initial training stage: stationary balance through the standard scripts/train.py.
"""
from wheel_legged_gym.envs.wheel_legged.wheel_legged_config import (
    WheelLeggedCfg, WheelLeggedCfgPPO,
)


class Heroleg26Cfg(WheelLeggedCfg):
    class env(WheelLeggedCfg.env):
        num_envs = 256
        episode_length_s = 20.0
        # Existing termination logic requires consecutive failing action steps.
        # At 100 Hz this resets after about 50-60 ms of base contact >10 N.
        # This is a balance-training rule, not a mechanical parameter.
        fail_to_terminal_time_s = 0.05

    class terrain(WheelLeggedCfg.terrain):
        mesh_type = "plane"
        curriculum = False

    class commands(WheelLeggedCfg.commands):
        # Learn stationary balance before expanding the motion-command range.
        curriculum = False

        class ranges(WheelLeggedCfg.commands.ranges):
            lin_vel_x = [0.0, 0.0]
            ang_vel_yaw = [0.0, 0.0]
            # Observation placeholder only; height rewards are disabled below.
            # The spawn height is not a calibrated loaded standing-height target.
            height = [0.334, 0.334]

    class init_state(WheelLeggedCfg.init_state):
        # New CAD body frame: +X nose, +Y left, +Z up.
        rot = [0., 0., 0., 1.]  # xyzw
        # About 10 mm collision-mesh clearance at the confirmed standing pose.
        pos = [0., 0., 0.334]
        # User-confirmed URDF angles: both J1=-25 deg, both J2=+20 deg.
        # Values below are radians; wheel zero angles remain unchanged.
        default_joint_angles = {
            "RJ1": -0.4363323129985824, "RJ2": 0.3490658503988659, "RJ3": 0.,
            "LJ1": -0.4363323129985824, "LJ2": 0.3490658503988659, "LJ3": 0.,
        }

    class asset(WheelLeggedCfg.asset):
        # Full-resolution geometry generated by the existing SDK-check helper.
        file = ("{WHEEL_LEGGED_GYM_ROOT_DIR}/../heroleg26_isaac_check/"
                "generated/heroleg26_obj.urdf")
        name = "heroleg26"
        body_forward_axis = [1., 0., 0.]
        leg_kinematics = "urdf_serial"
        recompute_inertia = False  # Keep the supplied URDF inertias.
        # Actual lengths and CAD zero offsets are read from the loaded URDF.
        l1 = 0.210
        l2 = 0.250
        foot_name = "_Link3"  # L_Link3 and R_Link3
        # A parked base must not count as successful wheel-supported standing.
        penalize_contacts_on = ["base_link"]
        terminate_after_contacts_on = ["base_link"]
        # Provisional 24 V continuous-output profile; see ACTUATORS.md.
        # Legs: 20 Nm, 100 rpm. Wheels: C620 3 Nm/469 rpm reference,
        # converted from 3591/187 to the total ratio 268/17.
        # Rated speed is a chosen operating ceiling, not a no-load maximum.
        actuator_limits = {
            "RJ1": {"effort": 20.0, "velocity": 10.471975511965978},
            "RJ2": {"effort": 20.0, "velocity": 10.471975511965978},
            "RJ3": {"effort": 2.462823725981621, "velocity": 59.82592010097471},
            "LJ1": {"effort": 20.0, "velocity": 10.471975511965978},
            "LJ2": {"effort": 20.0, "velocity": 10.471975511965978},
            "LJ3": {"effort": 2.462823725981621, "velocity": 59.82592010097471},
        }

    class sim(WheelLeggedCfg.sim):
        # 1 kHz external PD passed the plane fixed-base server check.
        # The 5 ms step caused sustained wheel-speed oscillation at Kd=0.2.
        dt = 0.001

    class control(WheelLeggedCfg.control):
        # Preserve the inherited 10 ms policy/action interval: 10 * 1 ms.
        decimation = 10
        # Clamp knee targets to raw URDF limits before PD; J1 remains continuous.
        clip_position_targets = True
        # Clamp velocity targets and stop driving farther into overspeed.
        # Braking torque remains available; this is not a measured motor curve.
        enforce_operating_speed = True

    class domain_rand(WheelLeggedCfg.domain_rand):
        # Start with the same nominal setup as the successful PPO smoke run.
        randomize_default_dof_pos = False
        randomize_base_mass = False
        randomize_base_com = False
        randomize_inertia = False
        randomize_friction = False
        randomize_restitution = False
        randomize_Kp = False
        randomize_Kd = False
        randomize_motor_torque = False
        randomize_action_delay = False
        push_robots = False
        # The original environment still samples root velocity on reset.

    class noise(WheelLeggedCfg.noise):
        add_noise = False

    class normalization(WheelLeggedCfg.normalization):
        clip_actions = 1.0

    class rewards(WheelLeggedCfg.rewards):
        class scales(WheelLeggedCfg.rewards.scales):
            # Avoid inheriting the original robot's 0.10-0.20 m height objective.
            base_height = 0.0
            base_height_enhance = 0.0


class Heroleg26CfgPPO(WheelLeggedCfgPPO):
    class policy(WheelLeggedCfgPPO.policy):
        init_noise_std = 0.2

    class algorithm(WheelLeggedCfgPPO.algorithm):
        learning_rate = 3.0e-4

    class runner(WheelLeggedCfgPPO.runner):
        experiment_name = "heroleg26_plane"
        run_name = "balance_stage1"
        max_iterations = 1000
        save_interval = 100
        resume = False
